     */
    const val SYSTEM =
        "你在一个手机聊天应用里回复，屏幕较窄，超出限制的表格会被客户端截断、用户看不到。请遵守：\n" +
            "1. Markdown 表格最多 10 列、100 行数据（表头不计入行数）。\n" +
            "2. 数据较多时拆成多个小表（建议每张表不超过 8 列、30 行），或改用列表/摘要。\n" +
            "3. 不要用超大表格堆砌数据。"
}
